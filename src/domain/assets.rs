#[derive(Debug, Clone, Serialize, Deserialize, ToSchema, sqlx::FromRow)]
pub struct Asset {
    pub id: Uuid,
    pub project_id: Uuid,
    pub dir_id: Option<Uuid>,
    pub name: String,
    /// Canonical path including the file name, e.g. `App Store/app-icon.png`.
    pub path: String,
    /// image | video | audio | other
    pub kind: String,
    pub blob_path: String,
    pub mime: String,
    pub width: Option<i32>,
    pub height: Option<i32>,
    pub duration_ms: Option<i32>,
    pub sha256: String,
    pub description: String,
    pub tags: Vec<String>,
    pub transcript: Option<Value>,
    pub bytes: Option<i64>,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
    /// Short-lived read URL (only filled by API responses).
    #[sqlx(skip)]
    #[serde(default)]
    pub read_url: Option<String>,
}

pub const ASSET_COLUMNS: &str = "id, project_id, dir_id, name, path, kind, blob_path, mime, \
     width, height, duration_ms, sha256, description, tags, transcript, bytes, created_at, \
     updated_at";

pub const DIR_COLUMNS: &str =
    "id, project_id, parent_id, name, path, description, created_at, updated_at";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AssetKind {
    Image,
    Video,
    Audio,
    Other,
}

impl AssetKind {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Image => "image",
            Self::Video => "video",
            Self::Audio => "audio",
            Self::Other => "other",
        }
    }

    pub fn parse(s: &str) -> Option<Self> {
        match s {
            "image" => Some(Self::Image),
            "video" => Some(Self::Video),
            "audio" => Some(Self::Audio),
            "other" => Some(Self::Other),
            _ => None,
        }
    }

    pub fn from_mime(mime: &str) -> Self {
        let m = mime.to_ascii_lowercase();
        if m.starts_with("image/") {
            Self::Image
        } else if m.starts_with("video/") {
            Self::Video
        } else if m.starts_with("audio/") {
            Self::Audio
        } else {
            Self::Other
        }
    }
}

// ── Path helpers ─────────────────────────────────────────────────────

/// Validate a single file/directory name.
pub fn validate_name(name: &str) -> Result<String, String> {
    let n = name.trim();
    if n.is_empty() {
        return Err("name is required".into());
    }
    if n.chars().count() > MAX_NAME_LEN {
        return Err(format!("name exceeds {MAX_NAME_LEN} characters"));
    }
    if n == "." || n == ".." {
        return Err("name cannot be . or ..".into());
    }
    if n.chars()
        .any(|c| c.is_control() || matches!(c, '/' | '\\' | '"' | '@'))
    {
        return Err("name cannot contain / \\ \" @ or control characters".into());
    }
    Ok(n.to_owned())
}

/// Normalize a user/agent-supplied path: strips a leading `@`, slashes, and empty segments.
/// The empty string is the (virtual) root.
pub fn normalize_path(raw: &str) -> Result<String, String> {
    let raw = raw.trim().trim_start_matches('@').trim_matches('"');
    let mut segs = Vec::new();
    for seg in raw.split('/') {
        if seg.trim().is_empty() {
            continue;
        }
        segs.push(validate_name(seg)?);
    }
    if segs.len() > MAX_PATH_DEPTH {
        return Err(format!("path is deeper than {MAX_PATH_DEPTH} levels"));
    }
    Ok(segs.join("/"))
}

/// Split `a/b/c` into (`a/b`, `c`). Root-level names have an empty parent.
pub fn split_path(path: &str) -> (&str, &str) {
    match path.rsplit_once('/') {
        Some((p, n)) => (p, n),
        None => ("", path),
    }
}

pub fn join_path(dir: &str, name: &str) -> String {
    if dir.is_empty() {
        name.to_owned()
    } else {
        format!("{dir}/{name}")
    }
}

/// Lowercase, trim, dedupe, cap tags.
pub fn normalize_tags(tags: &[String]) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for t in tags {
        let t = t.trim().to_lowercase();
        if t.is_empty() || t.chars().count() > 40 || out.contains(&t) {
            continue;
        }
        out.push(t);
        if out.len() >= 20 {
            break;
        }
    }
    out
}

fn escape_like(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('%', "\\%")
        .replace('_', "\\_")
}

