async fn path_taken(
    conn: &mut PgConnection,
    project_id: Uuid,
    path: &str,
    except_dir: Option<Uuid>,
    except_asset: Option<Uuid>,
) -> sqlx::Result<bool> {
    let (d, a): (bool, bool) = sqlx::query_as(
        "select exists(select 1 from asset_dirs where project_id = $1 and path = $2 \
                        and ($3::uuid is null or id <> $3)), \
                exists(select 1 from assets where project_id = $1 and path = $2 \
                        and ($4::uuid is null or id <> $4))",
    )
    .bind(project_id)
    .bind(path)
    .bind(except_dir)
    .bind(except_asset)
    .fetch_one(conn)
    .await?;
    Ok(d || a)
}

/// Insert the five seed directories (idempotent).
pub async fn seed_dirs(conn: &mut PgConnection, project_id: Uuid) -> sqlx::Result<()> {
    for (name, description) in SEED_DIRS {
        sqlx::query(
            "insert into asset_dirs (id, project_id, parent_id, name, path, description) \
             values ($1,$2,null,$3,$3,$4) on conflict (project_id, path) do nothing",
        )
        .bind(new_id())
        .bind(project_id)
        .bind(name)
        .bind(description)
        .execute(&mut *conn)
        .await?;
    }
    Ok(())
}

/// Create a directory. The parent must already exist (top-level directories need no parent).
pub async fn create_dir(
    pool: &PgPool,
    project_id: Uuid,
    path: &str,
    description: &str,
) -> AppResult<AssetDir> {
    let path = normalize_path(path).map_err(AppError::Invalid)?;
    if path.is_empty() {
        return Err(AppError::Invalid("directory path is required".into()));
    }
    if description.trim().is_empty() {
        return Err(AppError::Invalid(
            "every directory needs a description".into(),
        ));
    }
    let (parent_path, name) = split_path(&path);
    let mut tx = pool.begin().await?;
    let parent_id = if parent_path.is_empty() {
        None
    } else {
        Some(
            find_dir(&mut tx, project_id, parent_path)
                .await?
                .ok_or_else(|| {
                    AppError::Invalid(format!("parent directory \"{parent_path}\" does not exist"))
                })?
                .id,
        )
    };
    if path_taken(&mut tx, project_id, &path, None, None).await? {
        return Err(AppError::Conflict(format!("\"{path}\" already exists")));
    }
    let dir = sqlx::query_as::<_, AssetDir>(sqlx::AssertSqlSafe(format!(
        "insert into asset_dirs (id, project_id, parent_id, name, path, description) \
         values ($1,$2,$3,$4,$5,$6) returning {DIR_COLUMNS}"
    )))
    .bind(new_id())
    .bind(project_id)
    .bind(parent_id)
    .bind(name)
    .bind(&path)
    .bind(description.trim())
    .fetch_one(&mut *tx)
    .await?;
    tx.commit().await?;
    Ok(dir)
}

#[derive(Debug, Default)]
pub struct DirPatch {
    pub name: Option<String>,
    /// New parent directory path; empty string moves to the root.
    pub parent_path: Option<String>,
    pub description: Option<String>,
}

/// Rename / move / re-describe a directory. Descendant directory and asset paths follow.
pub async fn update_dir(pool: &PgPool, id: Uuid, patch: DirPatch) -> AppResult<AssetDir> {
    let mut tx = pool.begin().await?;
    let dir = sqlx::query_as::<_, AssetDir>(sqlx::AssertSqlSafe(format!(
        "select {DIR_COLUMNS} from asset_dirs where id = $1 for update"
    )))
    .bind(id)
    .fetch_one(&mut *tx)
    .await?;

    if let Some(d) = &patch.description
        && d.trim().is_empty()
    {
        return Err(AppError::Invalid(
            "every directory needs a description".into(),
        ));
    }

    let (cur_parent, cur_name) = split_path(&dir.path);
    let new_name = match &patch.name {
        Some(n) => validate_name(n).map_err(AppError::Invalid)?,
        None => cur_name.to_owned(),
    };
    let new_parent_path = match &patch.parent_path {
        Some(p) => normalize_path(p).map_err(AppError::Invalid)?,
        None => cur_parent.to_owned(),
    };
    let new_path = join_path(&new_parent_path, &new_name);

    if new_path != dir.path {
        if new_parent_path == dir.path || new_parent_path.starts_with(&format!("{}/", dir.path)) {
            return Err(AppError::Invalid(
                "cannot move a directory into itself".into(),
            ));
        }
        let new_parent_id = if new_parent_path.is_empty() {
            None
        } else {
            Some(
                find_dir(&mut tx, dir.project_id, &new_parent_path)
                    .await?
                    .ok_or_else(|| {
                        AppError::Invalid(format!(
                            "parent directory \"{new_parent_path}\" does not exist"
                        ))
                    })?
                    .id,
            )
        };
        if path_taken(&mut tx, dir.project_id, &new_path, Some(dir.id), None).await? {
            return Err(AppError::Conflict(format!("\"{new_path}\" already exists")));
        }
        // Rewrite the subtree: exact match and `old/…` descendants.
        sqlx::query(
            "update asset_dirs set path = $3 || substr(path, length($2) + 1), updated_at = now() \
              where project_id = $1 and (path = $2 or left(path, length($2) + 1) = $2 || '/')",
        )
        .bind(dir.project_id)
        .bind(&dir.path)
        .bind(&new_path)
        .execute(&mut *tx)
        .await?;
        sqlx::query(
            "update assets set path = $3 || substr(path, length($2) + 1), updated_at = now() \
              where project_id = $1 and left(path, length($2) + 1) = $2 || '/'",
        )
        .bind(dir.project_id)
        .bind(&dir.path)
        .bind(&new_path)
        .execute(&mut *tx)
        .await?;
        sqlx::query("update asset_dirs set name = $2, parent_id = $3 where id = $1")
            .bind(dir.id)
            .bind(&new_name)
            .bind(new_parent_id)
            .execute(&mut *tx)
            .await?;
    }
    if let Some(d) = &patch.description {
        sqlx::query("update asset_dirs set description = $2, updated_at = now() where id = $1")
            .bind(dir.id)
            .bind(d.trim())
            .execute(&mut *tx)
            .await?;
    }
    let out = sqlx::query_as::<_, AssetDir>(sqlx::AssertSqlSafe(format!(
        "select {DIR_COLUMNS} from asset_dirs where id = $1"
    )))
    .bind(dir.id)
    .fetch_one(&mut *tx)
    .await?;
    tx.commit().await?;
    Ok(out)
}

/// Delete a directory. Non-empty directories need `recursive`. Returns blob paths to remove.
pub async fn delete_dir(pool: &PgPool, id: Uuid, recursive: bool) -> AppResult<Vec<String>> {
    let mut tx = pool.begin().await?;
    let dir = sqlx::query_as::<_, AssetDir>(sqlx::AssertSqlSafe(format!(
        "select {DIR_COLUMNS} from asset_dirs where id = $1 for update"
    )))
    .bind(id)
    .fetch_one(&mut *tx)
    .await?;
    let (n_dirs, n_assets): (i64, i64) = sqlx::query_as(
        "select (select count(*) from asset_dirs where project_id = $1 \
                  and left(path, length($2) + 1) = $2 || '/'), \
                (select count(*) from assets where project_id = $1 \
                  and left(path, length($2) + 1) = $2 || '/')",
    )
    .bind(dir.project_id)
    .bind(&dir.path)
    .fetch_one(&mut *tx)
    .await?;
    if (n_dirs > 0 || n_assets > 0) && !recursive {
        return Err(AppError::Conflict(format!(
            "directory is not empty ({n_dirs} subdirectories, {n_assets} files); pass recursive=true"
        )));
    }
    let blobs: Vec<String> = sqlx::query_scalar(
        "delete from assets where project_id = $1 and left(path, length($2) + 1) = $2 || '/' \
         returning blob_path",
    )
    .bind(dir.project_id)
    .bind(&dir.path)
    .fetch_all(&mut *tx)
    .await?;
    sqlx::query("delete from asset_dirs where id = $1")
        .bind(dir.id)
        .execute(&mut *tx)
        .await?;
    tx.commit().await?;
    Ok(blobs)
}

#[derive(Debug, Clone, Serialize, ToSchema, sqlx::FromRow)]
pub struct AssetDirSummary {
    pub id: Uuid,
    pub parent_id: Option<Uuid>,
    pub name: String,
    pub path: String,
    pub description: String,
    /// Files directly inside this directory.
    pub file_count: i64,
    /// Subdirectories directly inside this directory.
    pub dir_count: i64,
}

pub async fn list_all_dirs(pool: &PgPool, project_id: Uuid) -> AppResult<Vec<AssetDirSummary>> {
    Ok(sqlx::query_as::<_, AssetDirSummary>(
        "select d.id, d.parent_id, d.name, d.path, d.description, \
                (select count(*) from assets a where a.dir_id = d.id) as file_count, \
                (select count(*) from asset_dirs c where c.parent_id = d.id) as dir_count \
           from asset_dirs d where d.project_id = $1 order by d.path",
    )
    .bind(project_id)
    .fetch_all(pool)
    .await?)
}

