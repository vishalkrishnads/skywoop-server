//! Asset manager: per-project directory tree, files, `@path` references, and search.
//!
//! Paths are canonical, `/`-separated, with no leading or trailing slash:
//! directory `App Store/Screenshots`, file `App Store/Screenshots/home.png`.
//! The root is the empty path and is virtual (never stored). Every directory carries a
//! description; plans and agents reference assets as `@App Store/Screenshots/home.png`.

